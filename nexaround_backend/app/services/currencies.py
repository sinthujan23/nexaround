def check_price_currency(value):
    """Upper-cased code if it is one of PRICE_CURRENCIES; None/"" pass through
    as None; anything else is refused (a schema validator raises on it)."""
    if value is None:
        return None
    code = str(value).strip().upper()
    if not code:
        return None
    if code not in PRICE_CURRENCIES:
        raise ValueError(f"Unknown currency '{code}'. Choose one from the list.")
    return code
