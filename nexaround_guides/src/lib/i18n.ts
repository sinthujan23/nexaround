// Languages for guide pages. English is the original; each guide can have a
// translation in src/content/translations/<lang>/<slug>.md, served at
// /<lang>/<pillar>/<slug>/. Interface text for each language is below:
// strings with {placeholders} are filled in with fill().

export const LANGS = ['en', 'es', 'fr', 'de', 'hi'] as const;
export type Lang = (typeof LANGS)[number];
export const TRANSLATED: Lang[] = ['es', 'fr', 'de', 'hi'];

export const LANG_NAMES: Record<Lang, string> = { en: 'English', es: 'Español', fr: 'Français', de: 'Deutsch', hi: 'हिन्दी' };
export const LOCALES: Record<Lang, string> = { en: 'en-GB', es: 'es-ES', fr: 'fr-FR', de: 'de-DE', hi: 'hi-IN' };

export const fill = (s: string, vars: Record<string, string | number> = {}) =>
  s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));

export const formatDateIn = (d: Date, lang: Lang) =>
  d.toLocaleDateString(LOCALES[lang], { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });

/** Where a guide lives in a language. */
export const guidePath = (lang: Lang, pillar: string, slug: string) => (lang === 'en' ? `/${pillar}/${slug}/` : `/${lang}/${pillar}/${slug}/`);

